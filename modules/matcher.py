def _match_lech_proc(clinic_name: str, catalog_df) -> dict | None:
    """
    Match Лечебная процедура using longest substring match.
    Longest match wins: 'колоноскопия с седацией' beats 'колоноскопия'.
    """
    cn_lower = re.sub(r'\s+', ' ', clinic_name.lower().strip())
    best_id  = None
    best_len = 0
    for keyword, sid in LECH_PROC_MAP.items():
        if keyword in cn_lower and len(keyword) > best_len:
            best_id  = sid
            best_len = len(keyword)
    if not best_id:
        return None
    cat_row = catalog_df[catalog_df["ID number"] == best_id]
    if cat_row.empty:
        return None
    name = safe_str(cat_row.iloc[0].get("Name RU", best_id))
    return {
        "matched_name":    name,
        "matched_id":      best_id,
        "confidence":      92,
        "comment":         "Лечебная процедура (таблица)",
        "top3_candidates": [{"service_id": best_id, "name": name,
                             "score": 92, "type": "Лечебная процедура"}],
        "method":          "lech_proc_table",
    }

