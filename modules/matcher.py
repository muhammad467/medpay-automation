# FUZZY FALLBACK ENGINE
# ═══════════════════════════════════════════════════════════════════════════════
def build_search_corpus(catalog_df: pd.DataFrame) -> list[tuple[str, str, str]]:
    """Build (normalized_name, original_name, id) for fuzzy fallback."""
    corpus = []
    for _, row in catalog_df.iterrows():
        rtype = safe_str(row.get("type", "")).strip()
        if rtype not in ALLOWED_CATALOG_TYPES:
            continue
        sid = safe_str(row.get("ID number", ""))
        for col in ("Name RU", "Name UZ", "Name KR"):
            name = safe_str(row.get(col, ""))
            if name:
                corpus.append((_normalize_fuzzy(name), name, sid))
    return corpus


def _fuzzy_top3(
    query: str,
    corpus: list[tuple[str, str, str]],
    catalog_df: pd.DataFrame,
) -> list[dict]:
    """Return top-3 matches using RapidFuzz."""
    norm_q    = _normalize_fuzzy(query)
    norm_q_ns = _normalize_fuzzy(_strip_noise(query))
    corp_norms = [c[0] for c in corpus]

    best: dict[str, dict] = {}   # service_id → best result

    for q in list({norm_q, norm_q_ns}):
        for scorer in [fuzz.token_sort_ratio, fuzz.token_set_ratio, fuzz.partial_ratio]:
            hits = process.extract(q, corp_norms, scorer=scorer,
                                   limit=5, score_cutoff=0)
            for _, score, idx in hits:
                _, orig, sid = corpus[idx]
                if sid not in best or score > best[sid]["score"]:
                    # Verify ID is valid
                    if sid in catalog_df["ID number"].values:
                        cat_r  = catalog_df[catalog_df["ID number"] == sid]
                        ctype  = cat_r.iloc[0]["type"] if not cat_r.empty else ""
                        name_r = safe_str(cat_r.iloc[0].get("Name RU","")) if not cat_r.empty else ""
                        name_u = safe_str(cat_r.iloc[0].get("Name UZ","")) if not cat_r.empty else ""
                        best[sid] = {
                            "service_id": sid,
                            "name_ru":    name_r,
                            "name_uz":    name_u,
                            "type":       ctype,
                            "score":      round(score),
                        }

    # Return top-3 sorted by score
    sorted_results = sorted(best.values(), key=lambda x: x["score"], reverse=True)
    return sorted_results[:3]


# ═══════════════════════════════════════════════════════════════════════════════
# MAIN MATCH FUNCTION
# ═══════════════════════════════════════════════════════════════════════════════
def match_service(
    clinic_name: str,
    corpus: list[tuple[str, str, str]],   # fuzzy corpus (always passed for fallback)
    catalog_df: pd.DataFrame,
) -> dict:
    """
    Match a clinic service name to the catalog.

    Returns:
        matched_name:    best match catalog name (RU)
        matched_id:      catalog ID (always set if any match found)
        confidence:      0-100 score
        comment:         human-readable label
        top3_candidates: list of top-3 {service_id, name_ru, score, type}
    """
    # ── Forced matches for known persistent wrong matches ────────────────────
    # These override the model when specific patterns are detected
    FORCED_MATCHES = {
        # Allergens
        'F262':      '1058114',  # баклажан IgE
        'Eggplant':  '1058114',
        'F303':      '1062116',  # палтус IgE
        'Halibut':   '1062116',
        # Immunogram
        'ACCURI':    '700213',   # иммунограмма проточная цитофлуориметрия
        # Фемофлор female
        'Femoflor':  '1023134',  # микрофлора влагалища
        'Фемофлор':  '1023134',
    }
    cn_upper = clinic_name.upper()
    for pattern, forced_id in FORCED_MATCHES.items():
        if pattern.upper() in cn_upper:
            cat_row = catalog_df[catalog_df['ID number'] == forced_id]
            if not cat_row.empty:
                name = cat_row.iloc[0].get('Name RU', forced_id)
                return {
                    'matched_name':    name,
                    'matched_id':      forced_id,
                    'confidence':      95,
                    'comment':         'Принудительное совпадение',
                    'top3_candidates': [{'service_id': forced_id, 'name': name,
                                         'score': 95, 'type': 'Анализы'}],
                    'method':          'forced',
                }
    # ── Лечебная процедура keyword lookup ─────────────────────────────────────
    lech_match = _match_lech_proc(clinic_name, catalog_df)
    if lech_match:
        return lech_match
      
    if not clinic_name:
        return _no_match()

    matcher = _get_embedding_matcher()

    # ── Path A: Fine-tuned embedding model ────────────────────────────────────
    if matcher.loaded:
        candidates = matcher.search(clinic_name, k=10)

        # Filter to allowed types
        candidates = [
            c for c in candidates
            if c["type"] in ALLOWED_CATALOG_TYPES
        ]

        if not candidates:
            return _no_match()

        # ── Contrast filter: if clinic name has NO contrast words,
        # prefer non-contrast catalog entries ─────────────────────────────────
        CONTRAST_WORDS = ["с контрастом", "с внутривенным", "болюсн",
                          "с в/в", "with contrast", "c contrast",
                          "внутривенное контрастирование"]
        clinic_lower = clinic_name.lower()
        clinic_has_contrast = any(w in clinic_lower for w in CONTRAST_WORDS)

        if not clinic_has_contrast:
            # Filter out contrast entries if non-contrast alternatives exist
            CATALOG_CONTRAST = ["с внутривенным контрастированием",
                                 "болюсное контрастирование",
                                 "с контрастным усилением",
                                 "с в/в контрастированием",
                                 "с болюсным"]
            non_contrast = [
                c for c in candidates
                if not any(w.lower() in (c.get("name_ru") or "").lower()
                           for w in CATALOG_CONTRAST)
            ]
            if non_contrast:
                candidates = non_contrast + [
                    c for c in candidates if c not in non_contrast
                ]

        best  = candidates[0]
        score = best["score"]

        # Block low-confidence matches — no ID assigned below 70%
        if score < MIN_CONFIDENCE:
            return _no_match()

        sid = best["service_id"]

        # Always verify ID exists in catalog
        if sid not in catalog_df["ID number"].values:
            return _no_match()

        # Get full catalog row for name
        cat_r    = catalog_df[catalog_df["ID number"] == sid]
        name_ru  = safe_str(cat_r.iloc[0].get("Name RU", "")) if not cat_r.empty else best["name_ru"]
        name_uz  = safe_str(cat_r.iloc[0].get("Name UZ", "")) if not cat_r.empty else best["name_uz"]
        display  = name_ru or name_uz or best["name_ru"]

        label    = confidence_label(score)

        # Format top-3 for UI display
        top3 = [
            {
                "service_id": c["service_id"],
                "name":       c["name_ru"] or c["name_uz"],
                "score":      c["score"],
                "type":       c["type"],
            }
            for c in candidates
        ]

        return {
            "matched_name":    display,
            "matched_id":      sid,
            "confidence":      score,
            "comment":         label,
            "top3_candidates": top3,
            "method":          "embedding",
        }

    # ── Path B: Fuzzy fallback ────────────────────────────────────────────────
    if not corpus:
        return _no_match()

    fuzzy_top3 = _fuzzy_top3(clinic_name, corpus, catalog_df)

    if not fuzzy_top3:
        return _no_match()

    best  = fuzzy_top3[0]
    score = best["score"]

    # Block low-confidence matches — no ID assigned below 70%
    if score < MIN_CONFIDENCE:
        return _no_match()

    sid   = best["service_id"]
    label = confidence_label(score)

    cat_r   = catalog_df[catalog_df["ID number"] == sid]
    name_ru = safe_str(cat_r.iloc[0].get("Name RU", "")) if not cat_r.empty else ""
    name_uz = safe_str(cat_r.iloc[0].get("Name UZ", "")) if not cat_r.empty else ""
    display = name_ru or name_uz

    top3 = [
        {
            "service_id": c["service_id"],
            "name":       c["name_ru"] or c["name_uz"],
            "score":      c["score"],
            "type":       c["type"],
        }
        for c in fuzzy_top3
    ]

    return {
        "matched_name":    display,
        "matched_id":      sid,
        "confidence":      score,
        "comment":         label,
        "top3_candidates": top3,
        "method":          "fuzzy",
    }


def _no_match() -> dict:
    return {
        "matched_name":    "-",
        "matched_id":      "-",
        "confidence":      0,
        "comment":         "Не найдено",
        "top3_candidates": [],
        "method":          "none",
    }


